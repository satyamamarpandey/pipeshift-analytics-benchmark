    name: str
    family: str
    desired: str          # RECOVER or ABSTAIN
    manifest: str         # how the delivered manifest relates to the delivered data
    metric_impact: bool   # whether accepting the observed data changes the metrics
    description: str
    default_intensity: float | None = None


